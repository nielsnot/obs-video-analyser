	obs_property_list_add_int(prop, obs_module_text("VS.Prop.ColorType.UV"), color_type_uv);

	prop = obs_properties_add_list(props, "graticule", obs_module_text("Graticule"), OBS_COMBO_TYPE_LIST,
				       OBS_COMBO_FORMAT_INT);
