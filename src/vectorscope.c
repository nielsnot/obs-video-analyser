#define VS_SIZE 256
#define N_GRATICULES 18
#define GRATICULES_IQ 256
#define GRATICULES_COLOR_MASK 3
#define SKIN_TONE_LINE 0x0054FF // BGR

#define RGB2Y_601(r, g, b) ((+306 * (r) + 601 * (g) + 117 * (b)) / 1024 + 0)
#define RGB2U_601(r, g, b) ((-150 * (r) - 296 * (g) + 448 * (b)) / 1024 + 128)
#define RGB2V_601(r, g, b) ((+448 * (r) - 374 * (g) - 72 * (b)) / 1024 + 128)

#define RGB2Y_709(r, g, b) ((+218 * (r) + 732 * (g) + 74 * (b)) / 1024 + 16)
#define RGB2U_709(r, g, b) ((-102 * (r) - 346 * (g) + 450 * (b)) / 1024 + 128)
#define RGB2V_709(r, g, b) ((+450 * (r) - 408 * (g) - 40 * (b)) / 1024 + 128)

/* Restrict the vectorscope to dark, middle or bright pixels, like a Lows / Mids / Highs split. */
enum luma_range_e {
	luma_range_all = 0,
	luma_range_lows = 1,
	luma_range_mids = 2,
	luma_range_highs = 3,
};
#define LUMA_LOW_MAX 85   // below one third of the range
#define LUMA_HIGH_MIN 170 // above two thirds of the range

enum color_type {
	color_type_white = 0,
	color_type_uv,
};

struct vss_source
{
	struct cm_source cm;

	gs_texture_t *tex_vs;
	uint8_t *tex_buf[2];
	int tex_cs[2];
	volatile int w_tex_buf;

	gs_image_file_t graticule_img;
	gs_vertbuffer_t *graticule_vbuf;
	gs_vertbuffer_t *graticule_line_vbuf;
	gs_effect_t *effect;

	int intensity;
	enum color_type color_type;
	int graticule;
	int graticule_color;
	int graticule_skintone_color;
	int graticule_cs;
	bool update_graticule;
	bool ring_scale;
	bool hue_ring;
	volatile int luma_range; // luma_range_e

	// snapshot reference, shown over the live trace while comparing
	volatile bool want_snapshot;
	volatile bool compare;
	uint8_t *ref_buf;
	bool ref_dirty;
	gs_texture_t *tex_ref;

	float zoom;
};

static void vss_update(void *, obs_data_t *);
static void vss_surface_cb(void *data, struct cm_surface_data *surface_data);

static const char *vss_get_name(void *unused)
{
	UNUSED_PARAMETER(unused);
	return obs_module_text("Vectorscope");
}

static void vss_snapshot_cb(void *data, calldata_t *cd)
{
	UNUSED_PARAMETER(cd);
	((struct vss_source *)data)->want_snapshot = true;
}

static void vss_compare_cb(void *data, calldata_t *cd)
{
	((struct vss_source *)data)->compare = calldata_bool(cd, "on");
}

static void *vss_create(obs_data_t *settings, obs_source_t *source)
{
	struct vss_source *src = bzalloc(sizeof(struct vss_source));

	src->cm.flags = CM_FLAG_CONVERT_YUV;
	src->zoom = 1.0f;
	cm_create(&src->cm, settings, source);
	cm_request(&src->cm, vss_surface_cb, src);

	{
		// The file is generated by
		// inkscape --export-png=data/vectorscope-graticule.png --export-area-page src/vectorscope-graticule.svg
		char *f = obs_module_file("vectorscope-graticule.png");
		gs_image_file_init(&src->graticule_img, f);
		if (!src->graticule_img.loaded)
			blog(LOG_ERROR, "Cannot load '%s'", f);
		obs_enter_graphics();
		gs_image_file_init_texture(&src->graticule_img);
		obs_leave_graphics();
		bfree(f);
	}

	obs_enter_graphics();
	src->effect = create_effect_from_module_file("vectorscope.effect");
	obs_leave_graphics();

	vss_update(src, settings);

	proc_handler_t *ph = obs_source_get_proc_handler(source);
	proc_handler_add(ph, "void va_snapshot()", vss_snapshot_cb, src);
	proc_handler_add(ph, "void va_set_compare(in bool on)", vss_compare_cb, src);

	return src;
}

static void vss_destroy(void *data)
{
	struct vss_source *src = data;

	obs_enter_graphics();
	gs_texture_destroy(src->tex_vs);
	gs_texture_destroy(src->tex_ref);
	gs_image_file_free(&src->graticule_img);
	vertexbuffer_destroy_safe(src->graticule_vbuf);
	vertexbuffer_destroy_safe(src->graticule_line_vbuf);
	obs_leave_graphics();

	cm_destroy(&src->cm);

	bfree(src->tex_buf[0]);
	bfree(src->tex_buf[1]);
	bfree(src->ref_buf);
	bfree(src);
}

static void vss_update(void *data, obs_data_t *settings)
{
	struct vss_source *src = data;
	cm_update(&src->cm, settings);

	src->intensity = (int)obs_data_get_int(settings, "intensity");
	if (src->intensity < 1)
		src->intensity = 1;

	src->color_type = (enum color_type)obs_data_get_int(settings, "color_type");

	int graticule = (int)obs_data_get_int(settings, "graticule");
	if ((graticule ^ src->graticule) & GRATICULES_IQ)
		src->update_graticule = 1;
	src->graticule = graticule;
	switch (graticule & GRATICULES_COLOR_MASK) {
	case 1:
		src->graticule_color = 0x80FFBF00;
		break; // amber
	case 2:
		src->graticule_color = 0x8000FF00;
		break; // green
	}

	src->ring_scale = obs_data_get_bool(settings, "ring_scale");
	src->hue_ring = obs_data_get_bool(settings, "hue_ring");
	src->luma_range = (int)obs_data_get_int(settings, "luma_range");

	int graticule_skintone_color = (int)obs_data_get_int(settings, "graticule_skintone_color") & 0xFFFFFF;
	if (graticule_skintone_color != src->graticule_skintone_color) {
		src->graticule_skintone_color = graticule_skintone_color;
		src->update_graticule = 1;
	}
}

